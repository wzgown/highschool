def load_plan_names():
    plan = {}
    for fn in glob.glob(os.path.join(DATA, "to_school_plan_*.csv")):
        short = os.path.basename(fn)[len("to_school_plan_"):-len(".csv")]
        dist = DIST_FULL.get(short, short + "区")
        names = set()
        with open(fn, encoding="utf-8-sig", newline="") as f:
            for r in csv.DictReader(f):
                n = (r.get("初中学校") or "").strip()
                if n:
                    names.add(n)
        plan[dist] = names
    return plan


def find_plan(dist, uname, plan_names):
    names = plan_names.get(dist, set())
    un = uname.replace("上海市", "").replace("中学", "").replace("学校", "")
    for n in names:
        nn = n.replace("上海市", "").replace("中学", "").replace("学校", "")
        if un and (un in nn or nn in un):
            return n
    return None


def main():
    plan_names = load_plan_names()

    # 1) 嘉定联网调研作为 supplement 字典
    jiading_supp = {}
    jd_file = os.path.join(DATA, "school_reputation_jiading.csv")
    if os.path.exists(jd_file):
        with open(jd_file, encoding="utf-8-sig", newline="") as f:
            for r in csv.DictReader(f):
                d = (r.get("区") or "").strip()
                s = (r.get("学校") or "").strip()
                try:
                    sc = float((r.get("声誉分") or "").strip())
                except ValueError:
                    sc = None
                if d and s and sc is not None:
                    jiading_supp[(d, s)] = (sc, (r.get("梯队") or "").strip(), (r.get("依据") or "").strip())

    out_rows = []
    seen = set()
    matched = 0
    nomatch = []

    with open(os.path.join(DATA, "school_tier_ranking.csv"), encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            dist = r["行政区"].strip()
            uname = r["学校名称"].strip()
            tier = r["梯队"].strip()
            prop = r["办学性质"].strip()
            tag = r["学校特色/民间标签"].strip()
            score = TIER_SCORE.get(tier)
            label = TIER_LABEL.get(tier, tier)
            if score is None:
                continue
            # resolve plan name
            key = (dist, uname)
            if key in TIER_MAP:
                pname = TIER_MAP[key]
            else:
                pname = find_plan(dist, uname, plan_names)
            if pname is None or pname not in plan_names.get(dist, set()):
                # 该校不在名额到校计划内（多为国际化/全市招生/无到校名额），无法进入排名，
                # 但仍作为机构梯队共识保留在此表，标注「未进到校计划」。
                nomatch.append((dist, uname, tier, score, label, prop, tag))
                continue
            matched += 1
            seen.add((dist, pname))
            # 来源：机构梯队列；若嘉定调研也覆盖，附上嘉定依据
            src = "机构公众号梯队列"
            if (dist, pname) in jiading_supp:
                jd_sc, jd_tier, jd_src = jiading_supp[(dist, pname)]
                src = f"机构公众号梯队列＋嘉定调研({jd_src})"
                # 梯队以 tier 表为准，但记录嘉定调研原始分作参考（不覆盖）
            out_rows.append([dist, pname, score, label, src])

    # 2) supplement: 嘉定调研里有、但 tier 表没覆盖的校
    for (d, s), (sc, tier, src) in jiading_supp.items():
        if (d, s) not in seen:
            out_rows.append([d, s, sc, tier, "嘉定联网调研(" + src + ")"])

    # 3) 未匹配但确属机构共识的校（不在名额到校计划内，无法进排名，仅作数据留存）
    for (d, u, t, sc, label, prop, tag) in nomatch:
        out_rows.append([d, u, sc, label, "机构公众号梯队列·未进到校计划"])

    # sort by district order then score desc
    out_rows.sort(key=lambda x: (x[0], -x[2]))

    out_file = os.path.join(DATA, "school_reputation.csv")
    with open(out_file, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["区", "学校", "声誉分", "梯队", "依据"])
        w.writerows(out_rows)

    print(f"[声誉] tier 表匹配率: {matched}/{matched+len(nomatch)} 成功(其余不在到校计划内) | 嘉定补 {len([1 for (d,s) in jiading_supp if (d,s) not in seen])} 校")
    print(f"[声誉] 总写入 {len(out_rows)} 行 -> {out_file}")
    if nomatch:
        print("[声誉] 未进到校计划(仅数据留存):")
        for d, u, t, sc, label, prop, tag in nomatch:
            print(f"   {d} | {u} | {t}")


if __name__ == "__main__":
    main()
